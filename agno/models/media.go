// Media inputs carried by a Message. A provider client converts these into its
// own wire format (content parts, blocks, inline data). Providers that cannot
// handle a given kind of media are expected to skip it rather than fail.

// Image is an image input, given either by URL or by raw bytes.
type Image struct {
	ID       string `json:"id,omitempty"`
	URL      string `json:"url,omitempty"`
	Data     []byte `json:"data,omitempty"`
	MimeType string `json:"mime_type,omitempty"`
	// Detail is the requested fidelity for providers that support it
	// ("auto", "low", "high"). Empty means the provider default.
	Detail string `json:"detail,omitempty"`
}

// Audio is an audio input, given either by URL or by raw bytes.
type Audio struct {
	ID       string `json:"id,omitempty"`
	URL      string `json:"url,omitempty"`
	Data     []byte `json:"data,omitempty"`
	MimeType string `json:"mime_type,omitempty"`
	// Format is the container format ("wav", "mp3"). Derived from MimeType when empty.
	Format string `json:"format,omitempty"`
}

// Video is a video input, given either by URL or by raw bytes.
type Video struct {
	ID       string `json:"id,omitempty"`
	URL      string `json:"url,omitempty"`
	Data     []byte `json:"data,omitempty"`
	MimeType string `json:"mime_type,omitempty"`
}

// File is a document input (PDF and similar), given either by URL or by raw bytes.
type File struct {
	ID       string `json:"id,omitempty"`
	Name     string `json:"name,omitempty"`
	URL      string `json:"url,omitempty"`
	Data     []byte `json:"data,omitempty"`
	MimeType string `json:"mime_type,omitempty"`
}

// AudioResponse is audio generated by a model as part of its answer.
type AudioResponse struct {
	ID         string `json:"id,omitempty"`
	Data       []byte `json:"data,omitempty"`
	MimeType   string `json:"mime_type,omitempty"`
	Transcript string `json:"transcript,omitempty"`
	ExpiresAt  int64  `json:"expires_at,omitempty"`
}

// ImageResponse is an image generated by a model as part of its answer.
type ImageResponse struct {
	ID            string `json:"id,omitempty"`
	URL           string `json:"url,omitempty"`
	Data          []byte `json:"data,omitempty"`
	MimeType      string `json:"mime_type,omitempty"`
	RevisedPrompt string `json:"revised_prompt,omitempty"`
}

// HasMedia reports whether the message carries any media input.
func (m Message) HasMedia() bool {
	return len(m.Images) > 0 || len(m.Audio) > 0 || len(m.Videos) > 0 || len(m.Files) > 0
}

// Resolve returns the image bytes and mime type, whether it was supplied inline
// or as a URL. Remote URLs are only fetched when fetchRemote is true; otherwise
// an empty payload is returned and the caller should pass the URL through to the
// provider as-is.
func (i Image) Resolve(fetchRemote bool) (data []byte, mimeType string, err error) {
	if len(i.Data) > 0 {
		return i.Data, i.mime(i.Data), nil
	}
	if i.URL == "" {
		return nil, "", fmt.Errorf("image %q has neither Data nor URL", i.ID)
	}
	if b, mt, ok := decodeDataURL(i.URL); ok {
		return b, firstNonEmpty(i.MimeType, mt), nil
	}
	if !fetchRemote {
		return nil, i.MimeType, nil
	}
	b, mt, err := fetchURL(i.URL)
	if err != nil {
		return nil, "", err
	}
	return b, firstNonEmpty(i.MimeType, mt, i.mime(b)), nil
}

// DataURL renders the image as an RFC 2397 data URL. Images that are already a
// remote URL are returned unchanged, since every provider accepts those directly.
func (i Image) DataURL() (string, error) {
	if len(i.Data) == 0 {
		if i.URL == "" {
			return "", fmt.Errorf("image %q has neither Data nor URL", i.ID)
		}
		return i.URL, nil
	}
	return encodeDataURL(i.Data, i.mime(i.Data)), nil
}

func (i Image) mime(data []byte) string {
	if i.MimeType != "" {
		return i.MimeType
	}
	return detectMime(data, "image/png")
}

