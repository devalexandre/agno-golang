// Filename returns the file name, falling back to a generic one derived from the
// mime type. Providers that take file uploads require a name.
func (f File) Filename() string {
	if f.Name != "" {
		return f.Name
	}
	mt := f.mime(f.Data)
	if _, sub, ok := strings.Cut(mt, "/"); ok {
		return "file." + sub
	}
	return "file"
}

func (f File) mime(data []byte) string {
	if f.MimeType != "" {
		return f.MimeType
	}
	return detectMime(data, "application/pdf")
}

// EncodeDataURL builds an RFC 2397 base64 data URL. Provider clients use it to
// inline media the API only accepts as base64.
func EncodeDataURL(data []byte, mimeType string) string {
	return encodeDataURL(data, mimeType)
}

// encodeDataURL builds an RFC 2397 base64 data URL.
func encodeDataURL(data []byte, mimeType string) string {
	return fmt.Sprintf("data:%s;base64,%s", mimeType, base64.StdEncoding.EncodeToString(data))
}

// decodeDataURL parses a base64 data URL. ok is false for any other input.
func decodeDataURL(s string) (data []byte, mimeType string, ok bool) {
	if !strings.HasPrefix(s, "data:") {
		return nil, "", false
	}
	meta, payload, found := strings.Cut(strings.TrimPrefix(s, "data:"), ",")
	if !found {
		return nil, "", false
	}
	mimeType = strings.TrimSuffix(meta, ";base64")
	if !strings.HasSuffix(meta, ";base64") {
		return []byte(payload), mimeType, true
	}
	decoded, err := base64.StdEncoding.DecodeString(payload)
	if err != nil {
		return nil, "", false
	}
	return decoded, mimeType, true
}

func fetchURL(url string) ([]byte, string, error) {
	resp, err := http.Get(url)
	if err != nil {
		return nil, "", fmt.Errorf("fetch media %s: %w", url, err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, "", fmt.Errorf("fetch media %s: unexpected status %s", url, resp.Status)
	}
	body, err := io.ReadAll(resp.Body)
	if err != nil {
		return nil, "", fmt.Errorf("read media %s: %w", url, err)
	}
	return body, resp.Header.Get("Content-Type"), nil
}

// detectMime sniffs the content type from the payload, falling back to def.
func detectMime(data []byte, def string) string {
	if len(data) == 0 {
		return def
	}
	ct := http.DetectContentType(data)
	if ct == "" || ct == "application/octet-stream" {
		return def
	}
	// DetectContentType appends charset for text types; media types never need it.
	if base, _, ok := strings.Cut(ct, ";"); ok {
		return strings.TrimSpace(base)
	}
	return ct
}

func firstNonEmpty(values ...string) string {
	for _, v := range values {
		if v != "" {
			return v
		}
	}
	return ""
}
