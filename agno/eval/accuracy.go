// judgeSystemPrompt is the base description given to the model acting as judge.
const judgeSystemPrompt = `You are an expert judge tasked with comparing the quality of an Agent's output to a user-provided expected output. You must assume the expected_output is correct - even if you personally disagree.

## Evaluation Inputs
- agent_input: The original task or query given to the Agent.
- expected_output: The correct response to the task (provided by the user).
    - NOTE: You must assume the expected_output is correct - even if you personally disagree.
- agent_output: The response generated by the Agent.

## Evaluation Criteria
- Accuracy: How closely does the agent_output match the expected_output?
- Completeness: Does the agent_output include all the key elements of the expected_output?

## Instructions
1. Compare the agent_output only to the expected_output, not what you think the expected_output should be.
2. Do not judge the correctness of the expected_output itself. Your role is only to compare the two outputs, the user provided expected_output is correct.
3. Follow the additional guidelines if provided.
4. Provide a detailed analysis including:
    - Specific similarities and differences
    - Important points included or omitted
    - Any inaccuracies, paraphrasing errors, or structural differences
5. Reference the criteria explicitly in your reasoning.
6. Assign a score from 1 to 10 (whole numbers only):
   1-2: Completely incorrect or irrelevant.
   3-4: Major inaccuracies or missing key information.
   5-6: Partially correct, but with significant issues.
   7-8: Mostly accurate and complete, with minor issues.
   9-10: Highly accurate and complete, matching the expected answer and given guidelines closely.
`

// judgeOutputInstructions tells the judge how to format its answer.
const judgeOutputInstructions = `
## Output Format
Respond with a single JSON object and nothing else:
{"accuracy_score": <integer between 1 and 10>, "accuracy_reason": "<detailed reasoning for the score>"}
`

// judgeResponse is the structured answer expected from the judge model.
type judgeResponse struct {
	AccuracyScore  int    `json:"accuracy_score"`
	AccuracyReason string `json:"accuracy_reason"`
}

// AccuracyEvaluation is the result of a single accuracy iteration.
type AccuracyEvaluation struct {
	Input          string `json:"input"`
	Output         string `json:"output"`
	ExpectedOutput string `json:"expected_output"`
	Score          int    `json:"score"`
	Reason         string `json:"reason"`
}

// AccuracyResult aggregates every AccuracyEvaluation of an accuracy run.
type AccuracyResult struct {
	Results     []AccuracyEvaluation `json:"results"`
	AvgScore    float64              `json:"avg_score"`
	MeanScore   float64              `json:"mean_score"`
	MinScore    float64              `json:"min_score"`
	MaxScore    float64              `json:"max_score"`
	StdDevScore float64              `json:"std_dev_score"`
}

// ComputeStats recomputes the aggregated scores from the collected evaluations.
func (r *AccuracyResult) ComputeStats() {
	scores := make([]float64, 0, len(r.Results))
	for _, result := range r.Results {
		scores = append(scores, float64(result.Score))
	}

	stats := computeStats(scores)
	r.AvgScore = stats.Avg
	r.MeanScore = stats.Avg
	r.MinScore = stats.Min
	r.MaxScore = stats.Max
	r.StdDevScore = stats.StdDev
}

// JSON serializes the result.
func (r *AccuracyResult) JSON() ([]byte, error) {
	return json.MarshalIndent(r, "", "  ")
}

// PrintSummary writes the aggregated scores to w. When w is nil, os.Stdout is used.
func (r *AccuracyResult) PrintSummary(w io.Writer) {
	if w == nil {
		w = os.Stdout
	}
	fmt.Fprintln(w, "=== Accuracy Evaluation Summary ===")
	fmt.Fprintf(w, "Number of Runs     : %d\n", len(r.Results))
	if len(r.Results) == 0 {
		return
	}
	fmt.Fprintf(w, "Average Score      : %.2f\n", r.AvgScore)
	fmt.Fprintf(w, "Minimum Score      : %.2f\n", r.MinScore)
	fmt.Fprintf(w, "Maximum Score      : %.2f\n", r.MaxScore)
	fmt.Fprintf(w, "Standard Deviation : %.2f\n", r.StdDevScore)
}

// PrintResults writes each individual evaluation to w. When w is nil, os.Stdout is used.
func (r *AccuracyResult) PrintResults(w io.Writer) {
	if w == nil {
		w = os.Stdout
	}
	for i, result := range r.Results {
		fmt.Fprintf(w, "=== Accuracy Evaluation Result #%d ===\n", i+1)
		fmt.Fprintf(w, "Input           : %s\n", result.Input)
		fmt.Fprintf(w, "Output          : %s\n", result.Output)
		fmt.Fprintf(w, "Expected Output : %s\n", result.ExpectedOutput)
		fmt.Fprintf(w, "Accuracy Score  : %d/10\n", result.Score)
		fmt.Fprintf(w, "Accuracy Reason : %s\n", result.Reason)
	}
}

// AccuracyEval evaluates how close the output of an agent is to an expected output.
// The comparison is delegated to a model acting as judge, which returns a score from 1 to 10.
type AccuracyEval struct {
	// Name of the evaluation.
	Name string
	// EvalID is a unique identifier for the evaluation. Generated when empty.
	EvalID string

	// Agent under evaluation.
	Agent AgentRunner
	// Input given to the agent.
	Input string
	// ExpectedOutput the agent output is compared against.
	ExpectedOutput string

	// Judge is the model used to grade the agent output.
	Judge Judge
	// AdditionalGuidelines given to the judge.
	AdditionalGuidelines []string
	// AdditionalContext given to the judge.
	AdditionalContext string

	// NumIterations is how many times the agent is run. Defaults to 1.
	NumIterations int

	// PrintSummary prints the aggregated scores after the run.
	PrintSummary bool
	// PrintResults prints every individual evaluation after the run.
	PrintResults bool
	// Writer used when printing. Defaults to os.Stdout.
	Writer io.Writer
	// FilePathToSaveResults persists the result as JSON when set.
	FilePathToSaveResults string

	// Result of the last run.
	Result *AccuracyResult
}

// evalID returns the evaluation ID, generating one when needed.
func (e *AccuracyEval) evalID() string {
	if e.EvalID == "" {
		e.EvalID = uuid.NewString()
	}
	return e.EvalID
}

// validate checks the evaluation is properly configured.
func (e *AccuracyEval) validate(requireAgent bool) error {
	if requireAgent && e.Agent == nil {
		return fmt.Errorf("eval: an agent is required to run the accuracy evaluation")
	}
	if e.Judge == nil {
		return fmt.Errorf("eval: a judge model is required to run the accuracy evaluation")
	}
	if e.Input == "" {
		return fmt.Errorf("eval: an input is required to run the accuracy evaluation")
	}
	if e.ExpectedOutput == "" {
		return fmt.Errorf("eval: an expected output is required to run the accuracy evaluation")
	}
	return nil
}

// iterations returns the configured number of iterations, defaulting to 1.
func (e *AccuracyEval) iterations() int {
	if e.NumIterations <= 0 {
		return 1
	}
	return e.NumIterations
}

// judgeDescription builds the system prompt for the judge model.
func (e *AccuracyEval) judgeDescription() string {
	var sb strings.Builder
	sb.WriteString(judgeSystemPrompt)

	if len(e.AdditionalGuidelines) > 0 {
		sb.WriteString("\n## Additional Guidelines\n")
		for _, guideline := range e.AdditionalGuidelines {
			sb.WriteString("- ")
			sb.WriteString(guideline)
			sb.WriteString("\n")
		}
	}

	if e.AdditionalContext != "" {
		sb.WriteString("\n## Additional Context\n")
		sb.WriteString(e.AdditionalContext)
		sb.WriteString("\n")
	}

	sb.WriteString(judgeOutputInstructions)
	return sb.String()
}

// judgeInput builds the user message handed to the judge model.
func (e *AccuracyEval) judgeInput(output string) string {
	return fmt.Sprintf(
		"<agent_input>\n%s\n</agent_input>\n\n<expected_output>\n%s\n</expected_output>\n\n<agent_output>\n%s\n</agent_output>",
		e.Input, e.ExpectedOutput, output,
	)
}

// evaluateOutput asks the judge model to grade a single agent output.
func (e *AccuracyEval) evaluateOutput(ctx context.Context, output string) (*AccuracyEvaluation, error) {
	messages := []models.Message{
		{Role: models.TypeSystemRole, Content: e.judgeDescription()},
		{Role: models.TypeUserRole, Content: e.judgeInput(output)},
	}

	response, err := e.Judge.Invoke(ctx, messages)
	if err != nil {
		return nil, fmt.Errorf("eval: judge model failed: %w", err)
	}
	if response == nil {
		return nil, fmt.Errorf("eval: judge model returned an empty response")
	}

	parsed, err := parseJudgeResponse(response.Content)
	if err != nil {
		return nil, err
	}

	return &AccuracyEvaluation{
		Input:          e.Input,
		Output:         output,
		ExpectedOutput: e.ExpectedOutput,
		Score:          parsed.AccuracyScore,
		Reason:         parsed.AccuracyReason,
	}, nil
}

// Run executes the agent NumIterations times and grades every output with the judge model.
func (e *AccuracyEval) Run(ctx context.Context) (*AccuracyResult, error) {
	if err := e.validate(true); err != nil {
		return nil, err
	}

	result := &AccuracyResult{}
	iterations := e.iterations()

	for i := 0; i < iterations; i++ {
		runResponse, err := e.Agent.Run(e.Input)
		if err != nil {
			return nil, fmt.Errorf("eval: agent run failed on iteration %d: %w", i+1, err)
		}

		output := strings.TrimSpace(runResponse.TextContent)
		if output == "" {
			return nil, fmt.Errorf("eval: agent returned an empty output on iteration %d", i+1)
		}

		evaluation, err := e.evaluateOutput(ctx, output)
		if err != nil {
			return nil, fmt.Errorf("eval: failed to evaluate iteration %d: %w", i+1, err)
		}

		result.Results = append(result.Results, *evaluation)
		result.ComputeStats()
	}

	return e.finish(result)
}

// RunWithOutput grades an output that was produced elsewhere, without running the agent.
func (e *AccuracyEval) RunWithOutput(ctx context.Context, output string) (*AccuracyResult, error) {
	if err := e.validate(false); err != nil {
		return nil, err
	}
	if strings.TrimSpace(output) == "" {
		return nil, fmt.Errorf("eval: an output is required to run the accuracy evaluation")
	}

	evaluation, err := e.evaluateOutput(ctx, output)
	if err != nil {
		return nil, err
	}

	result := &AccuracyResult{Results: []AccuracyEvaluation{*evaluation}}
	result.ComputeStats()

	return e.finish(result)
}

// finish stores, prints and returns the result according to the evaluation settings.
func (e *AccuracyEval) finish(result *AccuracyResult) (*AccuracyResult, error) {
	e.Result = result

	if e.FilePathToSaveResults != "" {
		if err := storeResultInFile(e.FilePathToSaveResults, e.Name, e.evalID(), TypeAccuracy, result); err != nil {
			return nil, err
		}
	}

	if e.PrintResults {
		result.PrintResults(e.Writer)
	}
	if e.PrintSummary {
		result.PrintSummary(e.Writer)
	}

	return result, nil
}

// parseJudgeResponse extracts the structured judge answer from a raw model response.
func parseJudgeResponse(content string) (*judgeResponse, error) {
	raw := extractJSONObject(content)
	if raw == "" {
		return nil, fmt.Errorf("eval: judge model returned an invalid response: %q", content)
	}

	var parsed judgeResponse
	if err := json.Unmarshal([]byte(raw), &parsed); err != nil {
		return nil, fmt.Errorf("eval: failed to parse the judge response: %w", err)
	}
	if parsed.AccuracyScore < 1 || parsed.AccuracyScore > 10 {
		return nil, fmt.Errorf("eval: judge returned an out of range score: %d", parsed.AccuracyScore)
	}

	return &parsed, nil
}

// extractJSONObject returns the outermost JSON object found in the given content.
// It tolerates markdown code fences and surrounding prose.
func extractJSONObject(content string) string {
	start := strings.Index(content, "{")
	end := strings.LastIndex(content, "}")
	if start == -1 || end == -1 || end < start {
		return ""
	}
	return content[start : end+1]
}
