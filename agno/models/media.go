// AudioFormat returns the short container name ("wav", "mp3") expected by the
// OpenAI audio input API.
func (a Audio) AudioFormat() string {
	if a.Format != "" {
		return a.Format
	}
	mt := a.MimeType
	if mt == "" {
		mt = detectMime(a.Data, "audio/wav")
	}
	if _, sub, ok := strings.Cut(mt, "/"); ok {
		switch sub {
		case "mpeg", "mp3":
			return "mp3"
		case "x-wav", "wave", "wav":
			return "wav"
		default:
			return sub
		}
	}
	return "wav"
}

